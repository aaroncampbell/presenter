<?php
/**
 * Presenter 2.0 asset registration.
 *
 * @package Presenter
 */

namespace Presenter;

/**
 * Registers built front-end assets without loading them on ordinary requests.
 */
final class Assets implements Hook_Provider {
	/**
	 * Whether the fixed asset handles have already been registered.
	 *
	 * @var bool
	 */
	private bool $registered = false;

	/**
	 * Plugin context.
	 *
	 * @var Plugin_Context
	 */
	private Plugin_Context $context;

	/**
	 * Create the asset registry.
	 *
	 * @param Plugin_Context $context Plugin context.
	 */
	public function __construct( Plugin_Context $context ) {
		$this->context = $context;
	}

	/**
	 * Register WordPress hooks.
	 */
	public function register_hooks(): void {
		add_action( 'init', array( $this, 'register' ), 5 );
	}

	/**
	 * Register modern presentation and block editor assets.
	 */
	public function register(): void {
		if ( $this->registered && $this->handles_are_registered() ) {
			return;
		}

		$frontend_asset        = $this->metadata( 'frontend' );
		$editor_asset          = $this->metadata( 'index' );
		$admin_migration_asset = $this->metadata( 'admin-migration' );

		wp_register_script(
			'presenter-frontend',
			$this->context->url() . 'build/frontend.js',
			$frontend_asset['dependencies'],
			$frontend_asset['version'],
			array(
				'in_footer' => true,
				'strategy'  => 'defer',
			)
		);
		wp_register_script(
			'presenter-block-editor',
			$this->context->url() . 'build/index.js',
			$editor_asset['dependencies'],
			$editor_asset['version'],
			array( 'in_footer' => true )
		);
		wp_register_style(
			'presenter-block-editor',
			$this->context->url() . 'build/index.css',
			array(),
			$editor_asset['version']
		);
		wp_style_add_data( 'presenter-block-editor', 'rtl', 'replace' );
		wp_register_script(
			'presenter-admin-migration',
			$this->context->url() . 'build/admin-migration.js',
			$admin_migration_asset['dependencies'],
			$admin_migration_asset['version'],
			array( 'in_footer' => true )
		);
		wp_register_style(
			'presenter-reveal-6',
			$this->context->url() . 'build/reveal/reveal.css',
			array(),
			$this->context->version()
		);
		wp_register_style(
			'presenter-frontend',
			$this->context->url() . 'build/frontend.css',
			array( 'presenter-reveal-6' ),
			$frontend_asset['version']
		);

		$this->registered = true;
	}

	/**
	 * Check whether every fixed modern asset handle remains registered.
	 *
	 * @return bool Whether registration can be skipped safely.
	 */
	private function handles_are_registered(): bool {
		return wp_script_is( 'presenter-frontend', 'registered' )
			&& wp_script_is( 'presenter-block-editor', 'registered' )
			&& wp_script_is( 'presenter-admin-migration', 'registered' )
			&& wp_style_is( 'presenter-block-editor', 'registered' )
			&& wp_style_is( 'presenter-reveal-6', 'registered' )
			&& wp_style_is( 'presenter-frontend', 'registered' );
	}

	/** Enqueue the bounded migration-screen client runner. */
	public function enqueue_admin_migration(): void {
		$this->register();
		wp_enqueue_script( 'presenter-admin-migration' );
	}

	/**
	 * Enqueue the modern presentation runtime and selected theme.
	 *
	 * @param string $theme_stylesheet_url Selected presentation theme URL.
	 */
	public function enqueue_presentation( string $theme_stylesheet_url ): void {
		$this->register();

		wp_enqueue_script( 'presenter-frontend' );
		wp_enqueue_style( 'presenter-frontend' );
		wp_deregister_style( 'reveal-theme' );
		wp_register_style(
			'reveal-theme',
			$theme_stylesheet_url,
			array( 'presenter-reveal-6' ),
			$this->context->version()
		);
		wp_enqueue_style( 'reveal-theme' );
	}

	/**
	 * Read the dependency metadata generated by wp-scripts.
	 *
	 * @param string $entrypoint Build entrypoint name.
	 * @return array{dependencies: array<int, string>, version: string} Asset metadata.
	 */
	private function metadata( string $entrypoint ): array {
		$metadata_file = $this->context->directory() . '/build/' . $entrypoint . '.asset.php';

		if ( ! is_readable( $metadata_file ) ) {
			return array(
				'dependencies' => array(),
				'version'      => $this->context->version(),
			);
		}

		$metadata = require $metadata_file;

		if ( ! is_array( $metadata ) ) {
			return array(
				'dependencies' => array(),
				'version'      => $this->context->version(),
			);
		}

		return array(
			'dependencies' => array_values( $metadata['dependencies'] ?? array() ),
			'version'      => (string) ( $metadata['version'] ?? $this->context->version() ),
		);
	}
}
